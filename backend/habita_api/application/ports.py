"""Puertos: contratos que el dominio necesita de la infraestructura."""
from __future__ import annotations

from typing import Protocol

from habita_api.domain.models import Chunk, Recording


class RecordingRepository(Protocol):
    def add(self, rec: Recording) -> None: ...
    def get(self, rec_id: str) -> Recording | None: ...
    def save(self, rec: Recording) -> None: ...
    def list_pending(self) -> list[Recording]: ...
    def upsert_chunk(self, chunk: Chunk) -> None: ...
    def chunks(self, rec_id: str) -> list[Chunk]: ...


class AudioStore(Protocol):
    def save(self, rec_id: str, seq: int, data: bytes, ext: str) -> str: ...
    def read(self, path: str) -> bytes: ...
    def delete_recording(self, rec_id: str) -> None: ...


class Transcriber(Protocol):
    name: str

    async def transcribe(self, audio: bytes, filename: str, mime: str, prompt: str) -> str: ...


class TextGenerator(Protocol):
    name: str

    async def generate(self, system: str, user: str) -> str: ...


class JobQueue(Protocol):
    def enqueue(self, rec_id: str) -> None: ...
